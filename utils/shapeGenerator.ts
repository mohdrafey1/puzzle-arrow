export function getShapeMask(
    shape: ShapeType | undefined,
    size: number,
): boolean[][] {
    if (!shape) {
        // Fill all true for random layout
        return Array(size)
            .fill(false)
            .map(() => Array(size).fill(true));
    }

    const maskMap = shape === "heart" ? HEART_MASKS : BIRD_MASKS;
    const mask = maskMap[size];

    if (!mask) {
        return Array(size)
            .fill(false)
            .map(() => Array(size).fill(true));
    }

    return mask.map((row) => row.map((cell) => cell === 1));
}
