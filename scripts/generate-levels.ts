import fs from "node:fs";
import path from "node:path";
import { generateLevel } from "../constants/levels";
import {
    CAMPAIGN_LEVEL_COUNT,
    CAMPAIGN_VERSION,
} from "../constants/levelDifficulty";
import { validateLevel } from "./level-validation";

const CHUNK_SIZE = 50;
const directory = path.resolve(__dirname, "../assets/levels");
const args = process.argv.slice(2);
function option(name: string, fallback: number): number {
    const index = args.indexOf(name);
    if (index < 0) return fallback;
    const value = Number(args[index + 1]);
    if (!Number.isInteger(value) || value < 1 || value > CAMPAIGN_LEVEL_COUNT) {
        throw new Error(
            `${name} must be an integer from 1 to ${CAMPAIGN_LEVEL_COUNT}.`,
        );
    }
    return value;
}
const from = option("--from", 1);
const to = option("--to", CAMPAIGN_LEVEL_COUNT);
if (from > to) throw new Error("--from must not exceed --to.");
fs.mkdirSync(directory, { recursive: true });
const firstChunk = Math.floor((from - 1) / CHUNK_SIZE);
const lastChunk = Math.floor((to - 1) / CHUNK_SIZE);
console.log(
    `Generating campaign v${CAMPAIGN_VERSION}; complete chunks ${firstChunk}–${lastChunk}.`,
);
for (let chunk = firstChunk; chunk <= lastChunk; chunk++) {
    const start = chunk * CHUNK_SIZE + 1;
    const end = Math.min((chunk + 1) * CHUNK_SIZE, CAMPAIGN_LEVEL_COUNT);
    const levels = [];
    for (let id = start; id <= end; id++) {
        const level = generateLevel(id);
        validateLevel(level);
        const { shape: _shape, ...stored } = level;
        // The campaign's masks are deterministic. Community/preview levels retain their own masks.
        levels.push(stored);
    }
    const destination = path.join(directory, `chunk-${chunk}.json`);
    // Replace only a complete chunk, leaving the previous file intact if generation fails.
    fs.writeFileSync(
        `${destination}.tmp`,
        `[\n${levels.map((level) => JSON.stringify(level)).join(",\n")}\n]\n`,
    );
    fs.renameSync(`${destination}.tmp`, destination);
    console.log(`Validated and wrote levels ${start}–${end}`);
}
// Always rebuild the index from its canonical specification. Reruns never append duplicate imports.
const chunkCount = Math.ceil(CAMPAIGN_LEVEL_COUNT / CHUNK_SIZE);
const imports = Array.from(
    { length: chunkCount },
    (_, c) => `import chunk${c} from './chunk-${c}.json';`,
).join("\n");
const names = Array.from({ length: chunkCount }, (_, c) => `chunk${c}`).join(
    ", ",
);
const index = `// Generated by scripts/generate-levels.ts.\nimport type { LevelData } from '../../constants/levels';\n${imports}\n\nexport type StoredLevelData = Omit<LevelData, 'shape'> & { shape?: boolean[][] };\nconst CHUNKS = [${names}] as unknown as StoredLevelData[][];\n\nexport function getStaticLevel(id: number): StoredLevelData | null {\n    if (!Number.isInteger(id) || id < 1 || id > ${CAMPAIGN_LEVEL_COUNT}) return null;\n    return CHUNKS[Math.floor((id - 1) / ${CHUNK_SIZE})][(id - 1) % ${CHUNK_SIZE}] ?? null;\n}\n`;
fs.writeFileSync(path.join(directory, "index.ts"), index);
